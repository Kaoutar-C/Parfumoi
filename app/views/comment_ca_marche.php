    <h1>Comment ça marche ?</h1>

    <h2 class="section-intro">🛍️ Tu veux acheter un parfum</h2>

    <section>
        <h2>1. Inscris-toi</h2>
        <p>Crée ton compte gratuitement en quelques secondes. Tu as juste besoin d'une adresse email.</p>
    </section>

    <section>
        <h2>2. Parcours le catalogue</h2>
        <p>Explore des centaines de parfums proposés par des particuliers. Filtre par catégorie, famille olfactive ou occasion.</p>
    </section>

    <section>
        <h2>3. Vérifie l'authenticité</h2>
        <p>Chaque parfum possède un numéro de série (batch code) visible sur l'annonce. Tu peux vérifier l'authenticité avant d'acheter.</p>
    </section>

    <section>
        <h2>4. Contacte le vendeur</h2>
        <p>Tu as trouvé ton bonheur ? Contacte directement le vendeur via son profil pour organiser la rencontre.</p>
    </section>

    <section>
        <h2>5. Échange en main propre</h2>
        <p>Les échanges se font uniquement en main propre pour garantir la sécurité de chaque transaction. Pas d'envoi postal.</p>
    </section>

    <h2 class="section-intro">💜 Tu veux vendre un parfum</h2>

    <section>
        <h2>1. Crée ton annonce</h2>
        <p>Prends une belle photo de ton parfum, ajoute une description honnête, le numéro de série et fixe ton prix.</p>
    </section>

    <section>
        <h2>2. Attends la validation</h2>
        <p>Chaque annonce est vérifiée par notre équipe avant d'être publiée. Cela garantit la qualité des annonces sur la plateforme.</p>
    </section>

    <section>
        <h2>3. Reçois des messages</h2>
        <p>Les acheteurs intéressés te contactent directement. Tu organises la rencontre à l'endroit qui te convient.</p>
    </section>

    <section>
        <h2>4. Finalise la vente</h2>
        <p>Remets le parfum en main propre et reçois ton paiement directement. Simple, sécurisé, sans intermédiaire.</p>
    </section>

    <section>
        <h2>🔒 Sécurité & confiance</h2>
        <p>Parfumoi vérifie chaque annonce et chaque numéro de série. En cas de problème, notre équipe est disponible via la page contact.</p>
    </section>

</div>