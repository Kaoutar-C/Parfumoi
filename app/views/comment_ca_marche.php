<h1>Comment ça marche ?</h1>

<section>
    <h2>1. Inscris-toi</h2>
    <p>Crée ton compte gratuitement en quelques secondes.</p>
</section>

<section>
    <h2>2. Dépose ton annonce</h2>
    <p>Prends une photo de ton parfum, ajoute une description et fixe ton prix.</p>
</section>

<section>
    <h2>3. Vérifie l'authenticité</h2>
    <p>Chaque parfum possède un numéro de série (batch code) qui permet de vérifier son authenticité.</p>
</section>

<section>
    <h2>4. Échange en main propre</h2>
    <p>Les échanges se font uniquement en main propre pour garantir la sécurité de chaque transaction.</p>
</section>
